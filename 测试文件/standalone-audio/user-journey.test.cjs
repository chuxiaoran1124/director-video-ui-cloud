// End-to-end user actions against the owned isolated staging site, not mocked APIs.
const assert = require('assert/strict')
const {execFileSync}=require('child_process')
const {chromium}=require('playwright')
const fs=require('fs'), path=require('path')
const base='http://127.0.0.1:18445'
const output=path.resolve(__dirname,'../../output/playwright/audio-user-journey')
const sample='E:/houduan/director-video-service-cloud-audio-20261015/测试文件/预发布验收/20261015-audio/fixtures/synthetic-zh-training.mp3'
async function main(){
  const command='docker exec director-video-audio-staging-backend python -c "import os,json; print(json.dumps({k:os.environ[k] for k in [\'PLATFORM_LOGIN_ENTRY_TOKEN\',\'AUDIO_TEST_ADMIN_PASSWORD\']}))"'
  const secret=JSON.parse(execFileSync('ssh.exe',['-o','BatchMode=yes','-o','ConnectTimeout=8','root@8.148.213.7',command],{encoding:'utf8'}))
  fs.mkdirSync(output,{recursive:true})
  const browser=await chromium.launch({headless:true,channel:'msedge'})
  let page; const steps=[]; const mark=name=>{steps.push(name);console.log('PASS',name)}
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true})
    await context.addInitScript(()=>{window.showSaveFilePicker=undefined})
    page=await context.newPage();const errors=[],proxy=[]
    page.on('pageerror',e=>errors.push(e.message))
    page.on('request',r=>{if(new URL(r.url()).pathname.includes('download-proxy'))proxy.push(true)})
    // Login by the actual form, including platform entry activation and redirect.
    await page.goto(base+'/?token='+encodeURIComponent(secret.PLATFORM_LOGIN_ENTRY_TOKEN)+'#/platform-login-entry')
    await page.getByPlaceholder('请输入用户名').waitFor({timeout:30000})
    await page.getByPlaceholder('请输入用户名').click()
    await page.getByPlaceholder('请输入用户名').fill('audio_stage_admin')
    await page.getByPlaceholder('请输入密码').fill(secret.AUDIO_TEST_ADMIN_PASSWORD)
    await page.getByRole('button',{name:'登录系统'}).click()
    await page.waitForURL(url=>!url.hash.includes('/login'),{timeout:30000})
    mark('login-through-visible-form')
    await page.goto(base+'/#/prior-disposal/voice-training')
    await page.getByRole('heading',{name:'声音训练',exact:true}).waitFor()
    const reuse=process.argv.find(arg=>arg.startsWith('--reuse='))?.split('=')[1]
    const suffix=reuse||Date.now(), training='用户模拟声音-'+suffix, dubbing='用户模拟配音-'+suffix
    if(!reuse){
    await page.getByRole('button',{name:'新建声音训练'}).click()
    let dialog=page.getByRole('dialog',{name:'新建声音训练',exact:true})
    await dialog.getByRole('button',{name:'提交任务',exact:true}).click()
    await page.getByText('请输入名称',{exact:true}).waitFor()
    assert(!(await dialog.innerText()).includes('泰语'))
    assert((await dialog.innerText()).includes('A2E'))
    await dialog.locator('.el-form-item').filter({hasText:'样本名称'}).locator('input').fill(training)
    await dialog.getByText('女',{exact:true}).click()
    // A valid WAV with only 2 seconds of audio must be rejected before submission.
    const short=Buffer.alloc(44+16000*2*2)
    short.write('RIFF',0);short.writeUInt32LE(short.length-8,4);short.write('WAVEfmt ',8)
    short.writeUInt32LE(16,16);short.writeUInt16LE(1,20);short.writeUInt16LE(1,22)
    short.writeUInt32LE(16000,24);short.writeUInt32LE(32000,28);short.writeUInt16LE(2,32)
    short.writeUInt16LE(16,34);short.write('data',36);short.writeUInt32LE(short.length-44,40)
    await dialog.locator('input[type=file]').setInputFiles({name:'too-short.wav',mimeType:'audio/wav',buffer:short})
    await page.getByText(/10.*60/).last().waitFor()
    await page.waitForFunction(()=>!document.querySelector('input[type=file]').files.length)
    mark('required-input-and-short-sample-validation')
    await dialog.locator('input[type=file]').setInputFiles(sample)
    await dialog.getByText(/synthetic-zh-training.mp3/).waitFor()
    await dialog.getByRole('button',{name:'提交任务',exact:true}).click()
    await dialog.waitFor({state:'hidden',timeout:60000})
    const trainingRow=page.locator('.el-table__body tr').filter({hasText:training})
    await trainingRow.waitFor({timeout:30000});mark('training-created-from-upload-form')
    await trainingRow.getByText('已完成',{exact:true}).waitFor({timeout:180000})
    await page.screenshot({path:path.join(output,'training-complete.png'),fullPage:true})
    mark('real-training-completed')
    }else{mark('reuse-already-browser-trained-voice-no-extra-clone')}
    await page.goto(base+'/#/generate-materials/audio-dubbing')
    await page.getByRole('heading',{name:'配音生成',exact:true}).waitFor()
    await page.getByRole('button',{name:'新建配音生成'}).click()
    dialog=page.getByRole('dialog',{name:'新建配音生成',exact:true})
    await dialog.locator('.el-form-item').filter({hasText:'配音名称'}).locator('input').fill(dubbing)
    const picker=dialog.locator('.voice-picker')
    await picker.getByPlaceholder('搜索可用声音').fill(training)
    await picker.getByRole('button',{name:'搜索',exact:true}).click()
    await picker.locator('.selected-row .el-select').click()
    await page.locator('.el-select-dropdown__item').filter({hasText:training}).click()
    await dialog.getByPlaceholder('请输入配音文案').fill('这是一次模拟用户操作测试。声音训练完成以后，选择声音生成配音，并验证试听和下载是否正常。')
    await dialog.getByRole('button',{name:'提交任务',exact:true}).click()
    await dialog.waitFor({state:'hidden',timeout:60000})
    const row=page.locator('.el-table__body tr').filter({hasText:dubbing})
    await row.getByText('已完成',{exact:true}).waitFor({timeout:180000})
    mark('new-voice-found-and-dubbing-completed-via-form')
    await row.getByRole('button',{name:'试听',exact:true}).click()
    await page.waitForFunction(()=>document.querySelector('audio')?.readyState>=2,null,{timeout:30000})
    const duration=await page.locator('audio').evaluate(a=>a.duration);assert(duration>0)
    await page.getByRole('dialog').locator('.el-dialog__headerbtn').click()
    await page.locator('audio').waitFor({state:'detached'});mark('direct-playback-and-close-release')
    const search=page.getByPlaceholder('按名称搜索')
    await search.fill('不存在的模拟任务-'+suffix);await search.press('Enter')
    await page.getByText('暂无任务',{exact:true}).waitFor()
    await search.fill(dubbing);await page.getByRole('button',{name:'搜索',exact:true}).click()
    await row.waitFor();await page.reload()
    await row.waitFor();assert.equal(await page.getByPlaceholder('按名称搜索').inputValue(),dubbing)
    mark('enter-button-search-empty-state-and-refresh-retention')
    await row.locator('.el-checkbox').click()
    const poll=page.waitForResponse(r=>r.url().endsWith('/audio-dubbing/paginate/'),{timeout:16000})
    await poll
    assert(await row.locator('input[type=checkbox]').isChecked());mark('selection-survives-silent-poll')
    const download=page.waitForEvent('download',{timeout:60000})
    await page.getByRole('button',{name:/批量下载/}).click()
    const file=await download;await file.saveAs(path.join(output,'user-dubbing.zip'))
    assert.equal(await file.failure(),null)
    const result=page.getByRole('dialog',{name:'音频下载结果',exact:true})
    await result.getByText('已打包下载 1 个音频',{exact:true}).waitFor()
    await page.screenshot({path:path.join(output,'download-success.png'),fullPage:true})
    assert.equal(proxy.length,0);mark('direct-zip-download-and-success-notice')
    await result.getByRole('button',{name:'知道了'}).click()
    const second=await context.newPage();await second.goto(base+'/#/generate-materials/audio-dubbing')
    await second.getByRole('heading',{name:'配音生成',exact:true}).waitFor()
    await second.reload();await second.getByRole('heading',{name:'配音生成',exact:true}).waitFor()
    mark('new-tab-and-reload-keep-login')
    await second.close()
    await page.setViewportSize({width:390,height:844})
    await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true})
    assert.deepEqual(errors,[])
    fs.writeFileSync(path.join(output,'result.json'),JSON.stringify({steps,training,dubbing,audioSeconds:duration,browserErrors:0},null,2))
    console.log(JSON.stringify({passed:steps.length,audioSeconds:duration,browserErrors:0}))
  }catch(error){if(page)await page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{});throw error}
  finally{await browser.close()}
}
main().catch(e=>{console.error(e.message);process.exitCode=1})
